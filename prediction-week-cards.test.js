const assert=require('assert');
const ui=require('./prediction-week-cards.js');
const cards=ui.buildCards([{week:4,complete:true,deadline:'2026-09-04T17:00:00Z'},{week:5,complete:false,deadline:'2026-09-11T17:00:00Z'}],{competition:'champions',week:1,complete:false,deadline:'2026-09-08T16:45:00Z'});
assert.deepStrictEqual(cards.map(x=>x.label),['Süper Lig 4. Hafta','Süper Lig 5. Hafta','Şampiyonlar Ligi 1. Hafta']);
assert.strictEqual(cards[0].target.type,'league');
assert.strictEqual(cards[0].target.week,4);
assert.strictEqual(cards[1].target.week,5);
assert.strictEqual(ui.selectionValue(cards[1]),'5');
assert.strictEqual(cards[2].target.type,'champions');
assert.strictEqual(cards[2].target.week,1);
assert.deepStrictEqual(cards.map(x=>x.theme),['super','super','champions']);
assert(ui.render(cards).includes('theme-super'));
assert(ui.render(cards).includes('theme-champions'));
assert.strictEqual(typeof ui.championsTabSelector,'function');
assert.strictEqual(ui.championsTabSelector(),'[data-tab="championsPred"]');
assert.strictEqual(ui.canEditBeforeWeekStart(Date.parse('2026-09-05T16:59:59Z'),Date.parse('2026-09-05T17:00:00Z')),true);
assert.strictEqual(ui.canEditBeforeWeekStart(Date.parse('2026-09-05T17:00:00Z'),Date.parse('2026-09-05T17:00:00Z')),false);
assert.strictEqual(cards[1].deadline,'2026-09-11T17:00:00Z');
assert.strictEqual(cards[2].deadline,'2026-09-08T16:45:00Z');
assert.strictEqual(ui.countdownText('2026-09-08T16:45:00Z','2026-09-06T06:45:00Z'),'⏳ Tahmine son 2 gün 10 saat');
assert.strictEqual(ui.countdownText('2026-09-08T16:45:00Z','2026-09-08T10:30:00Z'),'⏳ Tahmine son 7 saat');
assert.strictEqual(ui.countdownText('2026-09-08T16:45:00Z','2026-09-08T16:03:30Z'),'⏳ Tahmine son 42 dakika');
assert.strictEqual(ui.countdownText('2026-09-08T16:45:00Z','2026-09-08T16:45:00Z'),'🔒 Tahmin süresi doldu');
assert.strictEqual(ui.countdownText('2026-09-08T16:45:00Z','2026-09-06T06:45:00Z',true),'⏳ Maçların başlamasına 2 gün 10 saat');
assert.strictEqual(ui.countdownText('2026-09-08T16:45:00Z','2026-09-08T16:03:30Z',true),'⏳ Maçların başlamasına 42 dakika');
assert.strictEqual(ui.countdownText('2026-09-08T16:45:00Z','2026-09-08T16:45:00Z',true),'⚽ Maçlar başladı');
const missingMarkup=ui.render(cards,'2026-09-06T06:45:00Z');
assert(missingMarkup.includes('data-countdown-deadline="2026-09-11T17:00:00Z"'));
assert(missingMarkup.includes('⏳ Tahmine son'));
assert(missingMarkup.includes('data-countdown-complete="true"'));
assert(missingMarkup.includes('⚽ Maçlar başladı'));
const completeMarkup=ui.render([{label:'Süper Lig 5. Hafta',complete:true,deadline:'2026-09-08T16:45:00Z',theme:'super',target:{type:'league',week:5}}],'2026-09-06T06:45:00Z');
assert(completeMarkup.includes('⏳ Maçların başlamasına 2 gün 10 saat'));
assert(!missingMarkup.includes('undefined'));
console.log('prediction-week-cards ok');
