create table public.champions_league_fixtures (
  id bigint generated by default as identity primary key,
  season text not null,
  week integer not null check (week > 0),
  home_team text not null,
  away_team text not null,
  kickoff timestamptz not null,
  unique (season, week, home_team, away_team)
);

create index champions_league_fixtures_week_idx
  on public.champions_league_fixtures (season, week, kickoff);

create table public.champions_league_predictions (
  player_name text not null references public.players(name) on update cascade,
  fixture_id bigint not null references public.champions_league_fixtures(id) on delete cascade,
  home_score smallint not null check (home_score between 0 and 20),
  away_score smallint not null check (away_score between 0 and 20),
  updated_at timestamptz not null default now(),
  primary key (player_name, fixture_id)
);

create index champions_league_predictions_fixture_idx
  on public.champions_league_predictions (fixture_id);

create table public.champions_league_results (
  fixture_id bigint primary key references public.champions_league_fixtures(id) on delete cascade,
  home_score smallint not null check (home_score between 0 and 20),
  away_score smallint not null check (away_score between 0 and 20),
  updated_at timestamptz not null default now()
);

alter table public.champions_league_fixtures enable row level security;
alter table public.champions_league_predictions enable row level security;
alter table public.champions_league_results enable row level security;

revoke all on table public.champions_league_fixtures from anon, authenticated;
revoke all on table public.champions_league_predictions from anon, authenticated;
revoke all on table public.champions_league_results from anon, authenticated;
grant all on table public.champions_league_fixtures to service_role;
grant all on table public.champions_league_predictions to service_role;
grant all on table public.champions_league_results to service_role;

