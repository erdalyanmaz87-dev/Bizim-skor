create or replace function public.get_pending_game_announcement(p_token text)
returns table(
  announcement_key text,
  title text,
  body text,
  image_path text,
  ends_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
declare v_player text;
begin
  v_player := public.friend_session_player(p_token);
  if v_player is null then raise exception 'Oturum geçersiz veya süresi dolmuş'; end if;

  return query
  select a.announcement_key,a.title,a.body,a.image_path,a.ends_at
  from public.game_announcements a
  where a.enabled
    and now() >= a.starts_at
    and now() < a.ends_at
    and not exists (
      select 1 from public.game_announcement_acknowledgements x
      where x.announcement_id=a.id and x.player_name=v_player
    )
  order by a.starts_at desc
  limit 1;
end
$$;

create or replace function public.acknowledge_game_announcement(
  p_token text,
  p_announcement_key text
) returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare v_player text; v_announcement_id bigint;
begin
  v_player := public.friend_session_player(p_token);
  if v_player is null then raise exception 'Oturum geçersiz veya süresi dolmuş'; end if;

  select a.id into v_announcement_id
  from public.game_announcements a
  where a.announcement_key=p_announcement_key
    and a.enabled and now() >= a.starts_at and now() < a.ends_at;
  if v_announcement_id is null then return false; end if;

  insert into public.game_announcement_acknowledgements(announcement_id,player_name)
  values(v_announcement_id,v_player)
  on conflict (announcement_id, player_name) do nothing;
  return true;
end
$$;

revoke execute on function public.get_pending_game_announcement(text) from public, authenticated;
revoke execute on function public.acknowledge_game_announcement(text,text) from public, authenticated;
grant execute on function public.get_pending_game_announcement(text) to anon;
grant execute on function public.acknowledge_game_announcement(text,text) to anon;
