create table public.game_announcements (
  id bigint generated by default as identity primary key,
  announcement_key text not null unique,
  title text not null,
  body text not null,
  image_path text not null,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  check (ends_at > starts_at)
);

create table public.game_announcement_acknowledgements (
  announcement_id bigint not null references public.game_announcements(id) on delete cascade,
  player_name text not null references public.players(name) on update cascade,
  acknowledged_at timestamptz not null default now(),
  primary key (announcement_id, player_name)
);

alter table public.game_announcements enable row level security;
alter table public.game_announcement_acknowledgements enable row level security;
revoke all on table public.game_announcements from anon, authenticated;
revoke all on table public.game_announcement_acknowledgements from anon, authenticated;
grant all on table public.game_announcements to service_role;
grant all on table public.game_announcement_acknowledgements to service_role;

